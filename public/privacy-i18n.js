export function resolvePrivacyLocale(queryLocale, savedLocale, browserLocale) {
  const supported = Object.keys(privacyLanguages);
  for (const candidate of [queryLocale, savedLocale, browserLocale?.split("-")[0]?.toLowerCase()]) {
    if (supported.includes(candidate)) return candidate;
  }
  return "en";
}

if (typeof document !== "undefined") {
  const selector = document.getElementById("privacy-language");
  const url = new URL(location.href);
  let savedLocale;
  try { savedLocale = localStorage.getItem("mindes_locale"); } catch { /* storage unavailable */ }
  const initialLocale = resolvePrivacyLocale(url.searchParams.get("lang"), savedLocale, navigator.language);

  for (const [code, name] of Object.entries(privacyLanguages)) {
    const option = document.createElement("option");
    option.value = code;
    option.textContent = name;
    selector.append(option);
  }

  function render(code) {
    const dictionary = privacyTranslations[code];
    document.documentElement.lang = code;
    document.title = `${dictionary.title} — Mindes`;
    selector.setAttribute("aria-label", dictionary.language);
    selector.value = code;
    for (const element of document.querySelectorAll("[data-i18n]")) {
      element.textContent = dictionary[element.dataset.i18n];
    }
  }

  selector.addEventListener("change", () => {
    const code = selector.value;
    try { localStorage.setItem("mindes_locale", code); } catch { /* storage unavailable */ }
    url.searchParams.set("lang", code);
    history.replaceState(null, "", url);
    render(code);
  });

  render(initialLocale);
}
